// Turns the phones' experiment CSVs (raw/*.csv, from the Network tab's Save CSV) into
// summary.csv and summary.md: delivery, latency and overhead per chain length (TRD 2.12).
//   node experiments/field/analyze.mjs
//
// Each setting ("hops-1" … "hops-4") is one run: one phone sends N test SOS, the phone at the far
// end echoes each one. Latency is half the echo's round trip, timed on the sender's own clock,
// because phone clocks differ by up to a second.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const rawDir = join(here, 'raw');
const rows = readdirSync(rawDir)
  .filter((f) => f.endsWith('.csv'))
  .flatMap((f) => {
    const [header, ...lines] = readFileSync(join(rawDir, f), 'utf8').trim().split(/\r?\n/);
    const keys = header.split(',');
    return lines.map((line) => Object.fromEntries(line.split(',').map((v, i) => [keys[i], v])));
  });

const byLabel = Map.groupBy(rows, (r) => r.label);
const median = (xs) => (xs.length ? xs.toSorted((a, b) => a - b)[Math.floor((xs.length - 1) / 2)] : null);
const p90 = (xs) => (xs.length ? xs.toSorted((a, b) => a - b)[Math.floor((xs.length - 1) * 0.9)] : null);

const points = [...byLabel.entries()]
  .map(([label, rs]) => {
    const sent = new Set(rs.filter((r) => r.event === 'SENT').map((r) => r.sos_id));
    const farPhones = new Set(rs.filter((r) => r.event === 'ECHO_SENT').map((r) => r.phone));
    const received = rs.filter((r) => r.event === 'RECEIVED' && farPhones.has(r.phone) && sent.has(r.sos_id));
    const delivered = new Set(received.map((r) => r.sos_id));
    const rtts = rs.filter((r) => r.event === 'ECHO_RECEIVED' && sent.has(r.sos_id)).map((r) => Number(r.rtt_ms));
    const tx = rs.filter((r) => r.event === 'TX' && sent.has(r.sos_id)).length;
    const duplicates = rs.filter((r) => r.event === 'DUPLICATE' && sent.has(r.sos_id)).length;
    return {
      label,
      hops: median(received.map((r) => Number(r.hops))),
      phones: new Set(rs.map((r) => r.phone)).size,
      sent: sent.size,
      delivered: delivered.size,
      deliveryRatio: sent.size ? delivered.size / sent.size : 0,
      echoed: rtts.length,
      latencyMedianMs: rtts.length ? median(rtts) / 2 : null,
      latencyP90Ms: rtts.length ? p90(rtts) / 2 : null,
      txPerSos: sent.size ? tx / sent.size : 0,
      duplicatesPerSos: sent.size ? duplicates / sent.size : 0,
    };
  })
  .sort((a, b) => a.label.localeCompare(b.label));

const fix = (x, d = 2) => (x == null || Number.isNaN(x) ? '' : x.toFixed(d));
writeFileSync(
  join(here, 'summary.csv'),
  ['label,hops,phones,sent,delivered,delivery_ratio,echoed,latency_median_ms,latency_p90_ms,tx_per_sos,duplicates_per_sos']
    .concat(points.map((p) => [p.label, p.hops ?? '', p.phones, p.sent, p.delivered, fix(p.deliveryRatio, 3), p.echoed, fix(p.latencyMedianMs, 0), fix(p.latencyP90Ms, 0), fix(p.txPerSos), fix(p.duplicatesPerSos)].join(',')))
    .join('\n') + '\n',
);
const md = [
  '# Field results',
  '',
  'Forced chains on real phones (chain mode), test SOS from the first phone, echoed by the last. Latency is half the echo round trip. Generated by `node experiments/field/analyze.mjs`.',
  '',
  '| Setting | Radio hops | Sent | Delivered | Median latency | 90th pct latency | Transmissions per SOS | Duplicates per SOS |',
  '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
  ...points.map((p) => `| ${p.label} | ${p.hops ?? '–'} | ${p.sent} | ${p.delivered} (${Math.round(p.deliveryRatio * 100)}%) | ${p.latencyMedianMs == null ? "–" : `${fix(p.latencyMedianMs / 1000, 2)} s`} | ${p.latencyP90Ms == null ? "–" : `${fix(p.latencyP90Ms / 1000, 2)} s`} | ${fix(p.txPerSos, 1)} | ${fix(p.duplicatesPerSos, 1)} |`),
  '',
].join('\n');
writeFileSync(join(here, 'summary.md'), md);
console.log(md);
